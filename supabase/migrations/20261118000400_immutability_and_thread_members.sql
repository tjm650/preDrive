-- Event and audit records are append-only from client sessions.
drop policy if exists trip_events_admin_all on public.trip_events;
drop policy if exists absences_write on public.absences;
create policy absences_read_scoped on public.absences for select to authenticated using (
 private.is_guardian(child_id) or private.is_school_admin((select c.school_id from public.children c where c.id=child_id))
);
create policy absences_parent_insert on public.absences for insert to authenticated with check (
 reported_by=(select auth.uid()) and private.is_guardian(child_id)
);
create policy absences_admin_write on public.absences for update to authenticated using (
 private.is_school_admin((select c.school_id from public.children c where c.id=child_id))
) with check (private.is_school_admin((select c.school_id from public.children c where c.id=child_id)));
create policy absences_admin_delete on public.absences for delete to authenticated using (
 private.is_school_admin((select c.school_id from public.children c where c.id=child_id))
);

-- Restrict supervisor event creation to children actually on the assigned trip manifest.
drop policy if exists trip_events_supervisor_insert on public.trip_events;
create policy trip_events_supervisor_insert on public.trip_events for insert to authenticated with check (
 recorded_by=(select auth.uid())
 and private.is_assigned_supervisor(trip_id)
 and (
  child_id is null or exists(
   select 1 from public.trips t join public.route_children rc on rc.route_id=t.route_id
   where t.id=trip_events.trip_id and rc.child_id=trip_events.child_id
  )
 )
);

-- Supervisors may only change the trip lifecycle fields, never its tenant, bus, route or assignee.
revoke update on public.trips from authenticated;
grant update(status,started_at,ended_at) on public.trips to authenticated;
drop policy if exists trips_supervisor_update on public.trips;
create policy trips_supervisor_update on public.trips for update to authenticated
using (supervisor_id=(select auth.uid()))
with check (
 supervisor_id=(select auth.uid())
 and exists(select 1 from public.routes r where r.id=route_id and r.school_id=private.current_school_id())
 and exists(select 1 from public.buses b where b.id=bus_id and b.school_id=private.current_school_id())
);

-- A guardian can only acknowledge/read their own notification, not rewrite its routing or content.
revoke update on public.notifications from authenticated;
grant update(read_at,acknowledged_at) on public.notifications to authenticated;

-- Audit entries are generated by trusted database code and cannot be forged or edited by clients.
drop policy if exists audit_log_insert on public.audit_log;

-- Messaging uses explicit participants rather than inferring membership from arbitrary messages.
create table public.thread_members (
 id uuid primary key default gen_random_uuid(),
 thread_id uuid not null references public.threads(id) on delete cascade,
 user_id uuid not null references public.profiles(id) on delete cascade,
 created_at timestamptz not null default now(),
 unique(thread_id,user_id)
);
alter table public.thread_members enable row level security;
create policy thread_members_read on public.thread_members for select to authenticated using (
 user_id=(select auth.uid()) or exists(select 1 from public.threads th where th.id=thread_id and private.is_school_admin(th.school_id))
);
create policy thread_members_admin_manage on public.thread_members for all to authenticated using (
 exists(select 1 from public.threads th where th.id=thread_id and private.is_school_admin(th.school_id))
) with check (
 exists(select 1 from public.threads th where th.id=thread_id and private.is_school_admin(th.school_id))
);

drop policy if exists threads_access on public.threads;
create policy threads_read on public.threads for select to authenticated using (
 private.is_school_admin(school_id) or exists(select 1 from public.thread_members tm where tm.thread_id=threads.id and tm.user_id=(select auth.uid()))
);
create policy threads_admin_insert on public.threads for insert to authenticated with check (private.is_school_admin(school_id));
create policy threads_admin_update on public.threads for update to authenticated using (private.is_school_admin(school_id)) with check (private.is_school_admin(school_id));
create policy threads_admin_delete on public.threads for delete to authenticated using (private.is_school_admin(school_id));

drop policy if exists messages_read on public.messages;
drop policy if exists messages_insert on public.messages;
create policy messages_read on public.messages for select to authenticated using (
 sender_id=(select auth.uid()) or exists(select 1 from public.thread_members tm where tm.thread_id=messages.thread_id and tm.user_id=(select auth.uid()))
 or exists(select 1 from public.threads th where th.id=thread_id and private.is_school_admin(th.school_id))
);
create policy messages_insert on public.messages for insert to authenticated with check (
 sender_id=(select auth.uid()) and exists(select 1 from public.thread_members tm where tm.thread_id=thread_id and tm.user_id=(select auth.uid()))
);

-- Notification idempotency is per recipient, child, trip and event type (not global per child).
drop index if exists public.notifications_dedupe_trip_child_type;
create unique index notifications_dedupe_trip_child_type
on public.notifications (user_id,(params->>'trip_id'),(params->>'child_id'),type)
where params ? 'trip_id' and params ? 'child_id';

-- Recreate the RPC after hardening the audit trail; PIN hashes never leave Postgres.
create or replace function public.verify_pickup_pin(child_id uuid,pickup_id uuid,pin text)
returns boolean language plpgsql security definer set search_path = '' as $$
declare actor uuid := auth.uid();
declare stored_hash text;
declare failures integer;
declare child_school uuid;
declare allowed boolean;
begin
 if actor is null or pin is null or length(pin) not between 4 and 12 or pin !~ '^[0-9]+$' then return false; end if;
 select c.school_id into child_school from public.children c where c.id=verify_pickup_pin.child_id;
 if child_school is null then return false; end if;
 select exists(
  select 1 from public.guardianships g where g.child_id=verify_pickup_pin.child_id and g.guardian_id=actor
  union all
  select 1 from public.route_children rc join public.trips t on t.route_id=rc.route_id
  where rc.child_id=verify_pickup_pin.child_id and t.supervisor_id=actor and t.status='active'
 ) into allowed;
 if not allowed and not private.is_school_admin(child_school) then return false; end if;
 select count(*) into failures from private.pickup_pin_attempts a
 where a.actor_id=actor and a.child_id=verify_pickup_pin.child_id and not a.succeeded
 and a.attempted_at>now()-interval '15 minutes';
 if failures >= 5 then
  insert into private.pickup_pin_attempts(actor_id,child_id,succeeded) values(actor,verify_pickup_pin.child_id,false);
  insert into public.audit_log(school_id,actor_id,action,entity_type,entity_id,metadata)
  values(child_school,actor,'pickup_pin_rate_limited','authorized_pickup',pickup_id,jsonb_build_object('attempts',failures+1));
  return false;
 end if;
 select ap.pin_hash into stored_hash from public.authorized_pickups ap
 where ap.id=pickup_id and ap.child_id=verify_pickup_pin.child_id;
 if stored_hash is null then allowed := false;
 else allowed := crypt(pin,stored_hash)=stored_hash;
 end if;
 insert into private.pickup_pin_attempts(actor_id,child_id,succeeded) values(actor,verify_pickup_pin.child_id,allowed);
 insert into public.audit_log(school_id,actor_id,action,entity_type,entity_id,metadata)
 values(child_school,actor,case when allowed then 'pickup_pin_verified' else 'pickup_pin_failed' end,'authorized_pickup',pickup_id,
 jsonb_build_object('child_id',verify_pickup_pin.child_id));
 return allowed;
end $$;
revoke all on function public.verify_pickup_pin(uuid,uuid,text) from public,anon;
grant execute on function public.verify_pickup_pin(uuid,uuid,text) to authenticated;
